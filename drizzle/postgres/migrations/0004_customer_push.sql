BEGIN
  IF NEW."toStatus" IN ('placed','accepted','rejected','preparing','ready','out_for_delivery','delivered','cancelled','failed_delivery','returned') THEN
    INSERT INTO customer_push_events(order_event_id,order_id,user_id)
    SELECT NEW.id,o.id,o."customerId" FROM orders o WHERE o.id=NEW."orderId"
