export function marketLanguage(value: unknown): MarketLanguage {
  return value === "hi" || value === "hinglish" ? value : "en";
}
export function translate(language: MarketLanguage, message: string): string {
  return language === "en"
    ? message
    : (messages[message]?.[language === "hi" ? 0 : 1] ?? message);
}
